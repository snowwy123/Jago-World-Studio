function quaySignal(){
 const rate=16000,seconds=2,frames=rate*seconds;
 const bytes=new Uint8Array(44+frames*2),view=new DataView(bytes.buffer);
 const word=(at,text)=>bytes.set(new TextEncoder().encode(text),at);
 word(0,'RIFF');view.setUint32(4,bytes.length-8,true);word(8,'WAVE');word(12,'fmt ');
 view.setUint32(16,16,true);view.setUint16(20,1,true);view.setUint16(22,1,true);
 view.setUint32(24,rate,true);view.setUint32(28,rate*2,true);view.setUint16(32,2,true);view.setUint16(34,16,true);
 word(36,'data');view.setUint32(40,frames*2,true);
 for(let i=0;i<frames;i++){
  let sample=0;
  for(const [offset,frequency] of [[0,392],[.42,587.33],[.83,493.88]]){
   const t=i/rate-offset;if(t<0)continue;
   const envelope=Math.min(1,t/.02)*Math.exp(-5*t);
   sample+=envelope*(Math.sin(t*frequency*2*Math.PI)+.23*Math.sin(t*frequency*4.21*Math.PI));
  }
  view.setInt16(44+i*2,Math.round(sample*4600*Math.min(1,(frames-i)/320)),true);
 }
 let binary='';
 for(let i=0;i<bytes.length;i+=8192)binary+=String.fromCharCode(...bytes.subarray(i,i+8192));
 return {id:uid(),name:'Lantern Quay · three-bell signal',mime:'audio/wav',kind:'Sound effect',seconds,bytes:bytes.length,src:'data:audio/wav;base64,'+btoa(binary),credit:'Original Jago example audio',license:'MIT'};
}

